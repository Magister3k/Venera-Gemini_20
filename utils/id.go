package utils

import (
	"crypto/rand"
	"encoding/hex"
)

// GenerateID генерирует случайный уникальный идентификатор фиксированной длины (16 символов, hex).
// Используется для идентификации рабочих процессов в файле processes.toml (п.1.9 ТЗ).
// Применяется криптографически безопасный генератор (crypto/rand) для избежания коллизий.
func GenerateID() string {
	bytes := make([]byte, 8) // 8 байт = 16 шестнадцатеричных символов
	if _, err := rand.Read(bytes); err != nil {
		// В случае ошибки системного генератора случайных чисел (например, нехватка энтропии),
		// возвращаем резервный идентификатор, чтобы не обрушить систему.
		return "0000000000000000"
	}
	return hex.EncodeToString(bytes)
}
